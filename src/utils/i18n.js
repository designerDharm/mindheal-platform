export function t(key) {
  const currentLang = getSelectedLanguage();
  const currentLanguageCode = langCodes[currentLang] || "en";
  return dict[currentLanguageCode]?.[key] || key;
}

export async function handleLanguageChange(lang) {
  localStorage.setItem("mindheal-language", lang);
  
  // SSoT check: Call profile update if logged in
  const token = localStorage.getItem("mindheal-access-token");
  if (token) {
    try {
      await api.updateProfile({ language: lang });
    } catch (err) {
      console.error("Failed to sync language choice with SSoT backend", err);
    }
  }
}

export function translateDOM(rootElement) {
  // Translate all text nodes
  const walker = document.createTreeWalker(rootElement, NodeFilter.SHOW_TEXT, null, false);
  let node;
  const nodesToTranslate = [];
  
  while ((node = walker.nextNode())) {
    const text = node.nodeValue.trim();
    // Only process nodes with actual text containing alphabetical characters
    if (text && text.length > 1 && /[a-zA-Z]/.test(text)) {
      // Ignore text inside scripts or styles
      if (node.parentElement && ['SCRIPT', 'STYLE'].includes(node.parentElement.tagName)) continue;
      nodesToTranslate.push({ node, original: text });
    }
  }
  
  // Translate captured nodes
  nodesToTranslate.forEach(({ node, original }) => {
    const translated = t(original);
    if (translated && translated !== original) {
      node.nodeValue = node.nodeValue.replace(original, translated);
    }
  });
  
  // Translate placeholder attributes
  const inputs = rootElement.querySelectorAll('input[placeholder], textarea[placeholder]');
  inputs.forEach(input => {
    const original = input.getAttribute('placeholder');
    const translated = t(original);
    if (translated && translated !== original) {
      input.setAttribute('placeholder', translated);
    }
  });
}
